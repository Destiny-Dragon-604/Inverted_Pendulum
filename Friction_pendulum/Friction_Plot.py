# --- parse meta + data blocks ---
lines = raw.strip("\n").splitlines()
blank_idx = next(i for i, s in enumerate(lines) if s.strip() == "")
meta = pd.read_csv(io.StringIO("\n".join(lines[:blank_idx])))
data = pd.read_csv(io.StringIO("\n".join(lines[blank_idx+1:])))

